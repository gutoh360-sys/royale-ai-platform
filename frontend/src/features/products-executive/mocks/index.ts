function buildPortfolioSummary(): PortfolioSummary {
  const totalRevenue = mockProducts.reduce((s, p) => s + p.revenue, 0)
  const avgRevenue = totalRevenue / mockProducts.length
  const avgMargin = mockProducts.reduce((s, p) => s + p.margin, 0) / mockProducts.length
  const top10Revenue = [...mockProducts].sort((a, b) => b.revenue - a.revenue).slice(0, 10).reduce((s, p) => s + p.revenue, 0)
  const topSku = [...mockProducts].sort((a, b) => b.revenue - a.revenue)[0]
  const health = Math.round(
    (mockProducts.filter((p) => p.growth >= 0).length / mockProducts.length) * 40 +
    (mockProducts.filter((p) => p.margin >= 35).length / mockProducts.length) * 30 +
    (mockProducts.filter((p) => p.status !== "dog").length / mockProducts.length) * 30,
  )
  const avgGrowth = mockProducts.reduce((s, p) => s + p.growth, 0) / mockProducts.length

  return {
    totalProducts: mockProducts.length,
    activeProducts: mockProducts.filter((p) => p.status !== "dog").length,
    formattedActiveProducts: String(mockProducts.filter((p) => p.status !== "dog").length),
    categories: mockCategories.length,
    topSku: topSku.sku,
    topSkuName: topSku.name,
    topSkuRevenue: topSku.formattedRevenue,
    averageRevenuePerProduct: new Intl.NumberFormat("pt-BR", { style: "currency", currency: "BRL", notation: "compact" }).format(avgRevenue),
    averageMargin: `${avgMargin.toFixed(1)}%`,
    averageMarginValue: avgMargin,
    top10Concentration: `${((top10Revenue / totalRevenue) * 100).toFixed(1)}%`,
    top10ConcentrationValue: (top10Revenue / totalRevenue) * 100,
    totalRevenue: new Intl.NumberFormat("pt-BR", { style: "currency", currency: "BRL" }).format(totalRevenue),
    totalRevenueValue: totalRevenue,
    health,
    growth: Math.round(avgGrowth * 10) / 10,
  }
}

